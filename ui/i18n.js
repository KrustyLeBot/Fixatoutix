window.makeT = function (lang) {
  const table = window.I18N[lang] || window.I18N.fr;
  return (key, vars) =>
    (table[key] ?? window.I18N.fr[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] != null ? vars[k] : ""));
};
